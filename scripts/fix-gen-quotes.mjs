#!/usr/bin/env node
/**
 * Regenerate TypeScript image files from _progress.json with proper escaping
 */
import { writeFileSync, readFileSync } from 'fs'
import { join, dirname } from 'path'
import { fileURLToPath } from 'url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const OUTPUT_DIR = join(__dirname, '..', 'src/lib/data/images-generated')
const progress = JSON.parse(readFileSync(join(OUTPUT_DIR, '_progress.json'), 'utf-8'))

const allResults = {}
let totalPhotos = 0
for (const [slug, data] of Object.entries(progress)) {
  if (data.complete && data.photos) {
    allResults[slug] = data.photos
    totalPhotos += data.count
  }
}

console.log(`Services: ${Object.keys(allResults).length} | Photos: ${totalPhotos}`)

const SERVICES_PER_FILE = 8
const serviceList = Object.entries(allResults)
const fileCount = Math.ceil(serviceList.length / SERVICES_PER_FILE)

for (let i = 0; i < fileCount; i++) {
  const batch = serviceList.slice(i * SERVICES_PER_FILE, (i + 1) * SERVICES_PER_FILE)
  const batchNum = i + 4
  const varName = `serviceImagePool_gen${batchNum}`
  const fileName = `images-gen${batchNum}.ts`

  const lines = []
  lines.push('/**')
  lines.push(' * Auto-generated by scripts/generate-unsplash-images.mjs')
  lines.push(` * ${batch.length} services, ${batch.reduce((s, [, p]) => s + p.length, 0)} images`)
  lines.push(' * NE PAS MODIFIER MANUELLEMENT')
  lines.push(' */')
  lines.push('')
  lines.push('function unsplash(id: string, w = 800, h = 500): string {')
  lines.push('  return `https://images.unsplash.com/photo-${id}?auto=format&fit=crop&w=${w}&h=${h}&q=80`')
  lines.push('}')
  lines.push('')
  lines.push(`export const ${varName}: Record<string, { src: string; alt: string }[]> = {`)

  for (const [slug, photos] of batch) {
    lines.push(`  '${slug}': [`)
    for (const photo of photos) {
      const rawAlt = photo.alt || `Travaux de ${slug.replace(/-/g, ' ')}`
      // Use double quotes and escape any double quotes in the alt text
      const safeAlt = rawAlt.replace(/\\/g, '\\\\').replace(/"/g, '\\"')
      lines.push(`    { src: unsplash("${photo.id}"), alt: "${safeAlt}" },`)
    }
    lines.push('  ],')
  }

  lines.push('}')
  lines.push('')

  writeFileSync(join(OUTPUT_DIR, fileName), lines.join('\n'))
  console.log(`${fileName} - ${batch.length} services`)
}

console.log('Done!')
